import { useEffect, useRef, useState } from 'react';
import { Boxes, ExternalLink, Plus, Check, Trash2 } from 'lucide-react';
import clsx from 'clsx';
import {
  WORKSPACE_ID,
  listWorkspaces,
  openWorkspaceInNewWindow,
  deleteWorkspace,
} from '@/lib/storage';
import { toast } from '@/components/ui/Toast';

/**
 * Workspace instance switcher.
 *
 * Each browser tab/window carries a workspace id (see `storage.ts`).
 * Storage is namespaced per-id, so different windows are fully isolated.
 * This popover lets the user:
 *   - See the id of the current window
 *   - Jump to any other workspace instance (opens in a new window so the
 *     current one stays untouched)
 *   - Create a brand-new empty workspace instance
 *   - Delete an old one they no longer need
 *
 * The current workspace is never deletable from here — closing/reloading
 * the tab is the correct exit path.
 */
export function WorkspaceSwitcher() {
  const [open, setOpen] = useState(false);
  const [workspaces, setWorkspaces] = useState<string[]>([WORKSPACE_ID]);
  const rootRef = useRef<HTMLDivElement>(null);

  // Refresh the list whenever the popover opens — cheap enough (a single
  // IndexedDB keys() call) that we don't need to cache aggressively.
  useEffect(() => {
    if (!open) return;
    void listWorkspaces().then(setWorkspaces);
  }, [open]);

  // Click-outside to close. Keyboard `Escape` handled by native dialog
  // semantics of the button below.
  useEffect(() => {
    if (!open) return;
    const onDown = (e: MouseEvent) => {
      if (!rootRef.current?.contains(e.target as Node)) setOpen(false);
    };
    document.addEventListener('mousedown', onDown);
    return () => document.removeEventListener('mousedown', onDown);
  }, [open]);

  const openNew = () => {
    // Fresh id generated by the target window on load — no need to
    // pre-mint one here. Just open the same page without the `ws` param
    // and let storage.ts auto-provision.
    const url = new URL(window.location.href);
    url.searchParams.delete('ws');
    window.open(url.toString(), '_blank', 'noopener');
    setOpen(false);
  };

  const jumpTo = (id: string) => {
    if (id === WORKSPACE_ID) {
      setOpen(false);
      return;
    }
    openWorkspaceInNewWindow(id);
    setOpen(false);
  };

  const remove = async (id: string) => {
    if (id === WORKSPACE_ID) return;
    if (!window.confirm(`Delete workspace "${id}"? This clears its files and recents.`)) return;
    try {
      await deleteWorkspace(id);
      setWorkspaces((prev) => prev.filter((w) => w !== id));
      toast.success(`Deleted "${id}"`);
    } catch (err) {
      toast.error(err instanceof Error ? err.message : 'Delete failed');
    }
  };

  return (
    <div ref={rootRef} className="relative">
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        title={`Workspace: ${WORKSPACE_ID}`}
        aria-label="Workspace instances"
        aria-haspopup="menu"
        aria-expanded={open}
        className="inline-flex items-center gap-1.5 px-2 h-8 rounded-md text-xs text-slate-600 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition"
      >
        <Boxes size={14} />
        <span className="hidden md:inline max-w-[9ch] truncate">{WORKSPACE_ID}</span>
      </button>

      {open && (
        <div
          role="menu"
          className="absolute right-0 top-full mt-1 z-50 w-72 rounded-lg shadow-xl border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 py-1"
        >
          <div className="px-3 py-2 text-[10px] uppercase tracking-wider text-slate-500 dark:text-slate-400 flex items-center justify-between">
            <span>Workspaces ({workspaces.length})</span>
            <button
              type="button"
              onClick={openNew}
              className="inline-flex items-center gap-1 text-brand-600 hover:text-brand-500 normal-case text-xs"
              title="Open a fresh, empty workspace in a new window"
            >
              <Plus size={12} /> New
            </button>
          </div>
          <ul className="max-h-72 overflow-y-auto">
            {workspaces.map((id) => {
              const isCurrent = id === WORKSPACE_ID;
              return (
                <li key={id}>
                  <div
                    className={clsx(
                      'group flex items-center gap-1 px-3 py-1.5 text-sm',
                      isCurrent
                        ? 'bg-brand-50 dark:bg-brand-900/30 text-brand-700 dark:text-brand-300'
                        : 'hover:bg-slate-100 dark:hover:bg-slate-800',
                    )}
                  >
                    <button
                      type="button"
                      onClick={() => jumpTo(id)}
                      className="flex-1 flex items-center gap-2 min-w-0 text-left"
                      title={isCurrent ? 'This is the current workspace' : `Open "${id}" in a new window`}
                    >
                      {isCurrent ? (
                        <Check size={12} className="flex-shrink-0" />
                      ) : (
                        <ExternalLink size={12} className="flex-shrink-0 opacity-60" />
                      )}
                      <span className="truncate">{id}</span>
                    </button>
                    {!isCurrent && (
                      <button
                        type="button"
                        onClick={() => void remove(id)}
                        title={`Delete workspace "${id}"`}
                        aria-label={`Delete ${id}`}
                        className="opacity-0 group-hover:opacity-100 text-slate-400 hover:text-red-500 flex-shrink-0 transition-opacity"
                      >
                        <Trash2 size={12} />
                      </button>
                    )}
                  </div>
                </li>
              );
            })}
          </ul>
          <div className="px-3 py-2 text-[10px] text-slate-500 dark:text-slate-400 border-t border-slate-100 dark:border-slate-800">
            Windows are isolated. Duplicate a tab to share; open a new
            window for a fresh instance.
          </div>
        </div>
      )}
    </div>
  );
}
