export type ViewMode = 'split' | 'editor' | 'preview';
export type PreviewMode = 'html' | 'pdf';
export type Theme = 'light' | 'dark' | 'system';
/**
 * Concrete diagram theme. Maps 1:1 onto Mermaid's own built-in theme
 * names so the renderer just passes it straight through — no custom
 * colour surgery required. Derived from the app shell (dark shell →
 * `dark`, otherwise → `default`) so there is a single theme control.
 */
export type MermaidTheme = 'default' | 'dark';
export type Language = 'markdown' | 'json' | 'xml' | 'html';

export interface Document {
  id: string;
  title: string;
  content: string;
  updatedAt: number;
  createdAt: number;
  /** Editor language for this document. Optional for back-compat with docs
   *  saved before multi-format support landed — treat missing as 'markdown'. */
  language?: Language;
  /** Snapshot of `content` at load / last-save time. Used for dirty tracking
   *  and diff-on-close (Phase 4). Undefined means "unknown baseline". */
  original?: string;
  /** If this doc was extracted from an archive (docx / xlsx / zip / …),
   *  the id of that archive. Used by the sidebar Archive panel to group
   *  entries and by the tab strip to render an origin badge. */
  archiveId?: string;
  /** Path within the archive (e.g. `word/document.xml`). Preserved so the
   *  entry can be re-associated after a page reload. */
  archivePath?: string;
}

export interface DocStats {
  characters: number;
  charactersNoSpaces: number;
  words: number;
  sentences: number;
  paragraphs: number;
  readingTimeMinutes: number;
}

export interface TocItem {
  id: string;
  text: string;
  depth: number;
  /** For JSON/XML outlines: 1-based line where this node begins. */
  line?: number;
  /** For JSON/XML outlines: 0-based column where this node begins. */
  col?: number;
  /** Small badge shown after the label (e.g. `object`, `array[3]`). */
  hint?: string;
  /** Short string the preview can search for to focus this item. */
  needle?: string;
  /** For structured outlines: dotted path (e.g. `users[0].name`). */
  path?: string;
  /** Absolute source offset (0-based) where the item's *value* begins. */
  valueStart?: number;
  /** Absolute source offset (0-based) one past the end of the item's value. */
  valueEnd?: number;
  /** Absolute source offset where the *whole element* begins (key for JSON,
   *  opening `<` for XML). Used by "Copy element" actions. */
  startOffset?: number;
  /** Absolute source offset one past the end of the whole element. */
  endOffset?: number;
  /** 0-based count of prior siblings that share the same `needle`. Lets a
   *  preview walk N-many text matches to reach the right one. */
  occurrence?: number;
  /** XML only: `true` when the element is written as `<tag />`. When the
   *  user edits an empty self-closing tag we need to rewrite the whole
   *  element as `<tag>value</tag>` rather than splicing between the
   *  (equal) value offsets. */
  selfClosing?: boolean;
}

// ---------------------------------------------------------------------------
// Archives (docx / xlsx / pptx / epub / plain zip)
// ---------------------------------------------------------------------------
// A container file that unpacks into many text/binary entries. We surface
// its contents as a browsable tree in the sidebar so a `.docx` becomes an
// intuitive "folder of XML parts" rather than a single opaque blob.

export type ArchiveKind = 'docx' | 'xlsx' | 'pptx' | 'epub' | 'zip' | 'tex';

export interface ArchiveEntry {
  /** Full path inside the archive, e.g. `word/document.xml`. */
  path: string;
  /** Uncompressed byte size — surfaced in the tree UI as a hint. */
  size: number;
  /** Editor language when this entry is opened; undefined for binary. */
  language?: Language;
  /** True for entries we cannot decode as text (images, fonts, …). */
  isBinary?: boolean;
  /** Cached text content — populated on unpack for text-like entries.
   *  Undefined for binary. Kept on the entry (not the Document) so archives
   *  survive tab closures without needing to re-unpack. */
  content?: string;
  /** Base64 payload for binary entries the app itself created (PDF
   *  responses saved from cURL, image uploads, etc.). Not populated for
   *  entries unpacked from a real ZIP — those keep their bytes in the
   *  JSZip cache and re-serialize on export. */
  binaryBase64?: string;
  /** MIME type recorded when the entry was created — used by the preview
   *  layer to pick a renderer (application/pdf → `<embed>`). */
  mimeType?: string;
  /** Document id if this entry has been opened as a tab. Stale ids are
   *  ignored (looked up defensively). */
  docId?: string;
  /** Synthetic entry generated by us (e.g. a Markdown preview rendered from
   *  the DOCX body). Not part of the actual ZIP file listing — rendered in
   *  the sidebar tree with a distinct icon/label. */
  isRendered?: boolean;
  /** Raster image entry — content is a small Markdown wrapper embedding
   *  the image as a `data:` URL, so the preview pane can display it. */
  isImage?: boolean;
}

export interface Archive {
  id: string;
  /** Original filename (e.g. `MyReport.docx`). Displayed as the tree root. */
  name: string;
  kind: ArchiveKind;
  entries: ArchiveEntry[];
  /** Entry path that should be the "main view" (e.g. `word/document.xml`
   *  for docx). Opened by default on unpack. */
  primaryPath?: string;
}
